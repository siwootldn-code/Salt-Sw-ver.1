def tr(lang: str, key: str, default: str = "") -> str:
    """언어 팩에서 문자열 조회 (없으면 한국어 → 키 순서로 대체)"""
    pack = TRANSLATIONS.get(lang) or TRANSLATIONS["KO"]
    if key in pack:
        return pack[key]
    fallback = TRANSLATIONS["KO"].get(key)
    return fallback if fallback is not None else (default or key)


def step_action_label(action_value: str, lang: str = "KO") -> str:
    """시퀀스 동작 이름 조회 (RAMP_LOAD 등)"""
    return tr(lang, f"seq_action_{action_value}", action_value)


def metric_label(metric_key: str, lang: str = "KO") -> str:
    """배치 통계 물성 이름 조회 (peak_load_n 등)"""
    return tr(lang, f"batch_m_{metric_key}", metric_key)
